const char *device_text(bool english,const char *source) {
 if(!english || !source)return source;
 size_t low=0,high=sizeof(messages)/sizeof(messages[0]);
 while(low<high) {
  size_t mid=low+(high-low)/2;int order=strcmp(source,messages[mid].zh);
  if(!order)return messages[mid].en;
  if(order<0)high=mid;else low=mid+1;
 }
 return source;
}
